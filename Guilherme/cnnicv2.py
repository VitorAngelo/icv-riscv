def exportar_escala(escala, nome):
    flat = np.atleast_1d(escala).flatten()
    cabecalho = f"#ifndef {nome}_H\n#define {nome}_H\n\n"
    cabecalho += f"// Dimensoes: {list(flat.shape)}\n"
    cabecalho += f"#define {nome}_SIZE {len(flat)}\n"
    cabecalho += f"static const float {nome}[{len(flat)}] = {{\n    "
    linhas = [", ".join(f"{v:.10f}f" for v in flat[i:i+8]) for i in range(0, len(flat), 8)]
    cabecalho += ",\n    ".join(linhas)
    cabecalho += "\n};\n\n#endif\n"
    return cabecalho

# quantização int8
def quantizar_pesos_int8(pesos, por_canal=True):
    if por_canal:
        eixo = len(pesos.shape) - 1
        eixos_reduzir = tuple(i for i in range(len(pesos.shape) - 1) if i != eixo)
        max_abs = np.max(np.abs(pesos), axis=eixos_reduzir)
    else:
        max_abs = np.max(np.abs(pesos))
    max_abs = np.maximum(max_abs, 1e-8)
    escala = max_abs / 127.0
    escala_expandida = np.expand_dims(escala, axis=tuple(i for i in range(len(pesos.shape) - 1))) if por_canal else escala
    w_int = np.round(pesos / escala_expandida)
    w_int = np.clip(w_int, -127, 127).astype(np.int8)
    return w_int, escala

# quantização int32 
ESCALA_INT32 = 2**20

def quantizar_pesos_int32(pesos):
    return np.round(pesos * ESCALA_INT32).astype(np.int32)

# calibração das escalas de ativação
def calibrar_escalas(model, x_calib, n_samples=1000):
    nomes = ['conv1', 'conv2', 'conv3', 'dense1']
    escalas = {}
    entrada = model.layers[0].input
    for nome in nomes:
        camada = model.get_layer(nome)
        modelo_parcial = keras.Model(inputs=entrada, outputs=camada.output)
        ativ = modelo_parcial.predict(x_calib[:n_samples], verbose=0)
        max_abs = np.max(np.abs(ativ))
        escala = max_abs / 255.0
        escalas[nome] = escala
        print(f"{nome}: max_abs={max_abs:.4f}, escala={escala:.6f}")
    return escalas

escalas_ativ = calibrar_escalas(model, x_test, 1000)

# exporta escalas de ativação
for nome, esc in escalas_ativ.items():
    with open(f"{nome}_escala_ativ.h", "w") as f:
        cabecalho = f"#ifndef {nome}_escala_ativ_H\n#define {nome}_escala_ativ_H\n\n"
        cabecalho += f"#define {nome.upper()}_ESCALA_ATIV_ESCALA {esc}f\n\n#endif\n"
        f.write(cabecalho)

# exporta pesos e biases para todos os tipos
escala_entrada_conv1 = 1.0 / 255.0

for camada in ['conv1', 'conv2', 'conv3', 'dense1', 'output']:
    w, b = model.get_layer(camada).get_weights()

    # float32
    with open(f"{camada}_w_float.h", "w") as f:
        f.write(exportar_float(w, f"{camada}_w_float"))
    with open(f"{camada}_b_float.h", "w") as f:
        f.write(exportar_float(b, f"{camada}_b_float"))

    # int8
    w_int8, escala_peso = quantizar_pesos_int8(w, por_canal=True)
    with open(f"{camada}_w_int8.h", "w") as f:
        f.write(exportar_int8(w_int8, f"{camada}_w_int8"))
    with open(f"{camada}_escala.h", "w") as f:
        f.write(exportar_escala(escala_peso, f"{camada}_escala"))

    # bias int8 (usa escala por canal)
    if camada == 'conv1':
        escala_entrada = escala_entrada_conv1
    elif camada == 'conv2':
        escala_entrada = escalas_ativ['conv1']
    elif camada == 'conv3':
        escala_entrada = escalas_ativ['conv2']
    elif camada == 'dense1':
        escala_entrada = escalas_ativ['conv3']
    elif camada == 'output':
        escala_entrada = escalas_ativ['dense1']

    b_i32_int8 = np.round(b / (escala_entrada * escala_peso)).astype(np.int32)
    with open(f"{camada}_b_int32.h", "w") as f:
        f.write(exportar_int32(b_i32_int8, f"{camada}_b_int32"))

    # int32 (pesos e biases)
    w_int32 = quantizar_pesos_int32(w)
    with open(f"{camada}_w_int32.h", "w") as f:
        f.write(exportar_int32(w_int32, f"{camada}_w_int32"))

    b_i32_int32 = np.round(b * ESCALA_INT32 / escala_entrada).astype(np.int32)
    with open(f"{camada}_b_int32_i32.h", "w") as f:
        f.write(exportar_int32(b_i32_int32, f"{camada}_b_int32_i32"))

